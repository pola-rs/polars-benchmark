def convert_dat_to_parquet(input_dir: str, output_dir: str):
    """Convert generated .dat files to parquet format."""
    input_path = Path(input_dir)
    output_path = Path(output_dir)

    for table_name, schema in TPCDS_SCHEMAS.items():
        input_file = input_path / f"{table_name}.dat"
        output_file = output_path / f"{table_name}.parquet"

        if input_file.exists():
            try:
                pl.scan_csv(
                    input_file,
                    separator="|",
                    has_header=False,
                    schema=schema,
                    truncate_ragged_lines=True,
                ).sink_parquet(output_file)
                print(f"{table_name} converted successfully")
            except Exception as e:
                print(f"Error converting {table_name}: {e}")
        else:
            print(f"Missing: {input_file}")


if __name__ == "__main__":
    if len(argv) != 3:
        print("Usage: python script.py <input_dir> <output_dir>")
        exit(1)

    input_dir = argv[1]
    output_dir = argv[2]
    convert_dat_to_parquet(input_dir, output_dir)
